static int ufs_mbu_plat_poll_phy_ready(struct ufs_google_host *host)
{
	int ret;
	u32 data;

	if (!host->ufs_ss_mmio)
		return -EINVAL;

	/* 0xF: [3:2], [1:0] : MPHY_RX_BUSY_STATUS, MPHY_TX_BUSY_STATUS */
	ret = readl_poll_timeout(host->ufs_ss_mmio + REG_MPHY_CFGBUSY_STATUS,
				 data,
				 (data & (MPHY_TX_BUSY_STATUS_MASK |
					  MPHY_RX_BUSY_STATUS_MASK)) == 0,
				 MPHY_ENABLE_DELAY_US, MPHY_ENABLE_TIMEOUT_US);
	if (ret)
		dev_err(host->hba->dev,
			"PHY Tx, Rx busy status error: %x. MPHY_CFGBUSY_STATUS=0x%x\n",
			data,
			readl(host->ufs_ss_mmio + REG_MPHY_CFGBUSY_STATUS));

	return ret;
}

static int ufs_mbu_plat_config_cpm(struct ufs_google_host *host)
{
	struct ufs_hba *hba;
	struct mailbox_data req_data;
	int pmic = CORE_SUB_PMIC;
	int ret;

	hba = host->hba;

	if (!(host->caps & GCAP_DECOUPLE_UFS_EN))
		return 0;

	ret = da9188_mfd_mbox_request(hba->dev, &host->mbox);
	if (ret) {
		dev_err(hba->dev, "%s: request pmic mbox client failed (%d)",
			__func__, ret);
		return ret;
	}

	req_data.data[0] = pmic;
	req_data.data[1] = 0; /* set BUCKxxS_UFS_CFG = 0 */

	ret = da9188_mfd_mbox_request(hba->dev, &host->mbox);
	if (ret) {
		dev_err(hba->dev, "%s: request pmic mbox client failed (%d)",
			__func__, ret);
		return ret;
	}

	req_data.data[0] = pmic;
	req_data.data[1] = 0; /* set BUCKxxS_UFS_CFG = 0 */

	/* VCC */
	ret = da9188_mfd_mbox_send_req_blocking(hba->dev, &host->mbox,
						CPM_COMMON_PMIC_SERVICE,
						MB_PMIC_TARGET_REGISTER,
						MB_REG_CMD_SET_PMIC_REG_SINGLE,
						REG_PMIC_VCC, req_data);
	if (ret) {
		dev_err(hba->dev, "%s: send mbox req failed (%d)", __func__,
			ret);
		return ret;
	}

	/* VCCQ */
	ret = da9188_mfd_mbox_send_req_blocking(hba->dev, &host->mbox,
						CPM_COMMON_PMIC_SERVICE,
						MB_PMIC_TARGET_REGISTER,
						MB_REG_CMD_SET_PMIC_REG_SINGLE,
						REG_PMIC_VCCQ, req_data);
	if (ret) {
		dev_err(hba->dev, "%s: send mbox req failed (%d)", __func__,
			ret);
		return ret;
	}

	return 0;
}

static void ufs_mbu_plat_config_vs(struct ufs_google_host *host)
{
	ufs_top_csr_writel(host,
			   FIELD_PREP(UFS_R_VC_OVRD_EN_MASK, 1) |
				   FIELD_PREP(UFS_R_VC_OVRD_VAL_MASK, 1) |
				   FIELD_PREP(UFS_W_VC_OVRD_EN_MASK, 1) |
				   FIELD_PREP(UFS_W_VC_OVRD_VAL_MASK, 1),
			   REG_HSIOS_UFS_AXQOS_OVRD);
}

static void ufs_mbu_plat_set_refclk_control(struct ufs_google_host *host,
					    bool on)
{
	struct ufs_hba *hba = host->hba;
	u32 gating_wait_us;
	u32 val;

	gating_wait_us = hba->dev_info.clk_gating_wait_us ?:
				 DEFAULT_CLK_GATING_WAIT_US;

	val = readl(host->ufs_ss_mmio + REG_REFCLK_GATING_CONTROL);
	val = (val & ~REFCLK_GATE_ENABLE_MASK) |
	      FIELD_PREP(REFCLK_GATE_ENABLE_MASK, on);
	writel(val, host->ufs_ss_mmio + REG_REFCLK_GATING_CONTROL);

	/* bRefClkGatingWaitTime read from device */
	if (on) {
		writel(0, host->ufs_ss_mmio + REG_REFCLK_SWITCHON_TIME);
		writel(gating_wait_us,
		       host->ufs_ss_mmio + REG_REFCLK_SWITCHOFF_TIME);
	}
}

