class RaTimersTest : public ::testing::Test {
 public:
  void SetUp() override { ; }

  void TearDown() override { ; }

 protected:
  ras_timers_t ras_timers;
  ra_packet_t ra;
};

static uint64_t get_current_time_ms(void) {
  return static_cast<uint32_t>(std::chrono::duration_cast<std::chrono::milliseconds>(
      pw::chrono::SystemClock::now().time_since_epoch()).count());
}

static void ra_proxy_lifetime_expired(const ra_timers_t *ra_timers __attribute__((unused))) {
}

static void ra_proxy_refresh_expired(const ra_timers_t *ra_timers __attribute__((unused))) {
}

TEST_F(RaTimersTest, AddAndRemoveRaTimer) {
  const int parse_res = parse_ra_packet(ra_packet, sizeof(ra_packet), &ra);
  ASSERT_EQ(parse_res, 0);

  const int init_res = ra_timers_init(&ras_timers, ra_proxy_lifetime_expired,
                                      ra_proxy_refresh_expired);
  ASSERT_EQ(init_res, RA_TIMERS_RESULT_SUCCESS);

  const uint64_t cur_time_ms = get_current_time_ms();
  const int add_res = ra_timers_add_or_update(&ra);
  ASSERT_EQ(add_res, RA_TIMERS_RESULT_NEW_ENTRY);

  ra_timers_t *ra_timers = ra_timers_get(&ra);
  ASSERT_NE(ra_timers, nullptr);

  EXPECT_EQ(ra_timers->ra_packet.packet_length, ra.packet_length);
  EXPECT_EQ(std::memcmp(ra_timers->ra_packet.packet_buffer, ra.packet_buffer, ra.packet_length), 0);
  // The expected expire time is 3600 seconds later, with an allowable inaccuracy of 1 second.
  uint64_t expected_expire_time_ms = cur_time_ms + 3600 * 1000;
  EXPECT_LE(expected_expire_time_ms, ra_timers->min_expire_time_ms);
  EXPECT_GT(expected_expire_time_ms + 1000, ra_timers->min_expire_time_ms);

  ra_timers_remove(&ra);
  ra_timers = ra_timers_get(&ra);
  ASSERT_EQ(ra_timers, nullptr);

  ra_timers_deinit();
}

