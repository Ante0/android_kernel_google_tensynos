#define IP6_ALEN 16

/*
 * Structure of the IPv6 input metadata
 */
struct ipv6_input_metadata {
    /* Original packet associated with the corresponding metadata */
    void *packet;
    uint8_t src_device_port;
    uint8_t upstream_interface_mac[ETH_ALEN];
    void *ipv6_routing_table;
    uint8_t ip_version;
    uint8_t src_mac_addr[ETH_ALEN];
    uint8_t dst_mac_addr[ETH_ALEN];
    uint8_t src_ip_addr[IP6_ALEN];
    uint8_t dst_ip_addr[IP6_ALEN];
    uint8_t hop_limit;
};

/*
 * Structure of the IPv6 output metadata
 */
struct ipv6_output_metadata {
    /* Original packet associated with the corresponding metadata */
    void *packet;
    uint8_t dst_device_port;
    uint8_t src_mac_addr[ETH_ALEN];
    uint8_t dst_mac_addr[ETH_ALEN];
    uint8_t hop_limit;
    uint8_t routing_flag;
    /* Software solution do not need routing_entry_id field */
    uint16_t routing_entry_id;
    uint8_t direction;
    uint8_t ingress_flag;
};

