static void getTether4Key(Tether4Key * target,
                          struct ipv4_input_metadata *in_metadata) {
    memset(target, 0, sizeof(Tether4Key));
    target->l4Proto = (uint16_t) in_metadata->protocol;
    memcpy(&target->src4, &in_metadata->src_ip_addr, IP_ALEN);
    memcpy(&target->dst4, &in_metadata->dst_ip_addr, IP_ALEN);
    target->srcPort = in_metadata->src_port;
    target->dstPort = in_metadata->dst_port;
}

static void getUpstreamTether4Entry(Tether4Entry *target,
                                    struct ipv4_input_metadata *in_metadata,
                                    struct ipv4_output_metadata *out_metadata) {
    getTether4Key(&target->key, in_metadata);

    memset(&target->value, 0, sizeof(Tether4Value));
    memcpy(target->value.dstMac, out_metadata->dst_mac_addr, ETH_ALEN);
    memset(&target->value.mangle46, 0, sizeof(struct in6_addr));
    target->value.mangle46.s6_addr16[5] = 0xffff;
    memcpy(&target->value.mangle46.s6_addr32[3], out_metadata->src_ip_addr, IP_ALEN);
    target->value.manglePort = out_metadata->src_port;
    target->value.last_used = 0;
}

static void getDownstreamTether4Entry(Tether4Entry *target,
                                    struct ipv4_input_metadata *in_metadata,
                                    struct ipv4_output_metadata *out_metadata) {
    getTether4Key(&target->key, in_metadata);

    memset(&target->value, 0, sizeof(Tether4Value));
    memcpy(target->value.dstMac, out_metadata->dst_mac_addr, ETH_ALEN);
    memset(&target->value.mangle46, 0, sizeof(struct in6_addr));
    target->value.mangle46.s6_addr16[5] = 0xffff;
    memcpy(&target->value.mangle46.s6_addr32[3], out_metadata->dst_ip_addr, IP_ALEN);
    target->value.manglePort = out_metadata->dst_port;
    target->value.last_used = 0;
}
