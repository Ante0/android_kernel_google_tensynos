#include <cinttypes>

#include "ip.h"
#include "nep_helpers.h"

#define IP_ALEN 4

/*
 * Structure of the IPv4 input metadata
 */
struct ipv4_input_metadata {
    /* Original packet associated with the corresponding metadata */
    void *packet;
    uint8_t src_device_port;
    uint8_t upstream_interface_mac[ETH_ALEN];
    void *ipv4_nat_table;
    uint8_t ip_version;
    uint8_t src_mac_addr[ETH_ALEN];
    uint8_t dst_mac_addr[ETH_ALEN];
    uint8_t src_ip_addr[IP_ALEN];
    uint8_t dst_ip_addr[IP_ALEN];
    uint16_t src_port;
    uint16_t dst_port;
    uint8_t protocol;
    uint16_t hdr_csum;
    uint16_t tcp_udp_csum;
    uint8_t dscp;
};

/*
 * Structure of the IPv4 output metadata
 */
struct ipv4_output_metadata {
    /* Original packet associated with the corresponding metadata */
    void *packet;
    uint8_t dst_device_port;
    uint8_t src_mac_addr[ETH_ALEN];
    uint8_t dst_mac_addr[ETH_ALEN];
    uint8_t src_ip_addr[IP_ALEN];
    uint8_t dst_ip_addr[IP_ALEN];
    uint16_t src_port;
    uint16_t dst_port;
    uint16_t hdr_csum;
    uint16_t tcp_udp_csum;
    uint8_t nat_flag;
    /* Software solution do not need nat_entry_id field */
    uint16_t nat_entry_id;
    uint8_t direction;
    uint8_t ingress_flag;
};

