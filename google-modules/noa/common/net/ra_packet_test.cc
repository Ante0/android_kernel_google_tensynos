class RaPacketTest : public ::testing::Test {
 public:
  void SetUp() override { ; }

  void TearDown() override { ; }

 protected:
  ra_packet_t ra;
};

TEST_F(RaPacketTest, BasicRaPacketParsing) {
  const int ret = parse_ra_packet(ra_packet, sizeof(ra_packet), &ra);

  ASSERT_EQ(ret, 0);
  EXPECT_EQ(ra.packet_length, sizeof(ra_packet));
  EXPECT_EQ(std::memcmp(ra.packet_buffer, ra_packet, sizeof(ra_packet)), 0);

  // Check parsed lifetime data
  EXPECT_EQ(ra.router_lifetime, (uint32_t)3600);
  EXPECT_EQ(ra.min_pio_valid_lifetime, (uint32_t)2592000);
  EXPECT_EQ(ra.min_rio_route_lifetime, (uint32_t)0xffffffff); // No RIO in this packet
  EXPECT_EQ(ra.min_rdnss_lifetime, (uint32_t)1209600);

  // Check that key option indices were found
  EXPECT_NE(ra.router_lifetime_idx, -1);
  EXPECT_NE(ra.pio_valid_lifetime_idx, -1);
  EXPECT_NE(ra.pio_preferred_lifetime_idx, -1);
  EXPECT_NE(ra.rdnss_lifetime_idx, -1);
  EXPECT_EQ(ra.rio_route_lifetime_idx, -1); // RIO not present
  EXPECT_NE(ra.mtu_option_idx, -1);
  EXPECT_NE(ra.slla_option_idx, -1);

  // Verify router lifetime section
  ASSERT_NE(ra.router_lifetime_idx, -1);
  const packet_section_t& rlt_section = ra.packet_sections[ra.router_lifetime_idx];
  EXPECT_EQ(rlt_section.type, SECTION_TYPE_LIFETIME);
  EXPECT_EQ(rlt_section.start, (uint32_t)ICMP6_RA_ROUTER_LIFETIME_OFFSET);
  EXPECT_EQ(rlt_section.length, (uint32_t)ICMP6_RA_ROUTER_LIFETIME_LEN);
  EXPECT_EQ(rlt_section.lifetime, (uint32_t)3600);

  // Verify PIO valid lifetime section
  ASSERT_NE(ra.pio_valid_lifetime_idx, -1);
  const packet_section_t& pio_vlt_section = ra.packet_sections[ra.pio_valid_lifetime_idx];
  EXPECT_EQ(pio_vlt_section.type, SECTION_TYPE_LIFETIME);
  EXPECT_EQ(pio_vlt_section.start, (uint32_t)126 + ICMP6_PREFIX_OPTION_VALID_LIFETIME_OFFSET);
  EXPECT_EQ(pio_vlt_section.length, (uint32_t)ICMP6_PREFIX_OPTION_VALID_LIFETIME_LEN);
  EXPECT_EQ(pio_vlt_section.lifetime, (uint32_t)2592000);

  // Verify PIO preferred lifetime section
  ASSERT_NE(ra.pio_preferred_lifetime_idx, -1);
  const packet_section_t& pio_plt_section = ra.packet_sections[ra.pio_preferred_lifetime_idx];
  EXPECT_EQ(pio_plt_section.type, SECTION_TYPE_LIFETIME);
  EXPECT_EQ(pio_plt_section.start, (uint32_t)126 + ICMP6_PREFIX_OPTION_VALID_LIFETIME_OFFSET +
            ICMP6_PREFIX_OPTION_VALID_LIFETIME_LEN);
  EXPECT_EQ(pio_plt_section.length, (uint32_t)ICMP6_PREFIX_OPTION_PREFERRED_LIFETIME_LEN);
  EXPECT_EQ(pio_plt_section.lifetime, (uint32_t)604800);

  // Verify RDNSS lifetime section
  ASSERT_NE(ra.rdnss_lifetime_idx, -1);
  const packet_section_t& rdnss_section = ra.packet_sections[ra.rdnss_lifetime_idx];
  EXPECT_EQ(rdnss_section.type, SECTION_TYPE_LIFETIME);
  EXPECT_EQ(rdnss_section.start, (uint32_t)86 + ICMP6_4_BYTE_LIFETIME_OFFSET);
  EXPECT_EQ(rdnss_section.length, (uint32_t)ICMP6_4_BYTE_LIFETIME_LEN);
  EXPECT_EQ(rdnss_section.lifetime, (uint32_t)1209600);

  // Verify MTU section
  ASSERT_NE(ra.mtu_option_idx, -1);
  const packet_section_t& mtu_section = ra.packet_sections[ra.mtu_option_idx];
  EXPECT_EQ(mtu_section.type, SECTION_TYPE_MATCH);
  EXPECT_EQ(mtu_section.start, (uint32_t)78);
  EXPECT_EQ(mtu_section.length, (uint32_t)8);
  EXPECT_EQ(mtu_section.lifetime, (uint32_t)0);

  // Verify SLLA section
  ASSERT_NE(ra.slla_option_idx, -1);
  const packet_section_t& slla_section = ra.packet_sections[ra.slla_option_idx];
  EXPECT_EQ(slla_section.type, SECTION_TYPE_MATCH);
  EXPECT_EQ(slla_section.start, (uint32_t)70);
  EXPECT_EQ(slla_section.length, (uint32_t)8);
  EXPECT_EQ(slla_section.lifetime, (uint32_t)0);
}

TEST_F(RaPacketTest, GenerateProxiedRaPacket) {
  const int ret = parse_ra_packet(ra_packet, sizeof(ra_packet), &ra);
  ASSERT_EQ(ret, 0);

  const int result = generate_proxied_packet(&ra);
  ASSERT_EQ(result, 0);

  EXPECT_EQ(std::memcmp(ra.proxied_packet, proxied_ra_packet, sizeof(proxied_ra_packet)), 0);
}

